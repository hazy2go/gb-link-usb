def bold(v):
    # Thicken strokes by 1 px to the right, but never close a 1 px gap (keeps W, M, # readable).
    return v | ((v >> 1) & ~(v << 1) & 0xFF)

out = ['; Generated by rom/mkfont.py: ASCII 0x20-0x5F, 8 bytes per glyph (1 bpp).', 'Font:']
for code in range(0x20, 0x60):
    rows = G[chr(code)]
    bs = []
    for r in range(8):
        bits = rows[r] if r < 7 and rows[r] else '.....'
        v = 0
        for i, ch in enumerate(bits.ljust(5, '.')):
            if ch == '#': v |= 0x80 >> (i + 1)   # 1 px left margin
        bs.append(bold(v))
    out.append('    db ' + ','.join(f'${b:02X}' for b in bs) + f'  ; {chr(code)!r}')
out.append('FontEnd:')

# Big font: each 5x7 row doubled to 14 rows (rows 1..14 of 16), made bold by OR-ing a 1 px right shift.
BIG = '0123456789,.$-'
out.append('; BigFont: ' + BIG + ', 16 bytes per glyph (1 bpp, 8x16)')
out.append('BigFont:')
for ch in BIG:
    rows = G[ch]
    bs = [0]
    for r in range(7):
        v = 0
        for i, c in enumerate(rows[r].ljust(5, '.')):
            if c == '#': v |= 0x80 >> i          # no left margin: bold glyph uses 6 columns
        v = bold(v)
        bs += [v, v]
    bs.append(0)
    out.append('    db ' + ','.join(f'${b:02X}' for b in bs) + f'  ; {ch!r}')
out.append('BigFontEnd:')

# Logo tiles
import os
here = os.path.dirname(os.path.abspath(__file__))
sh = [int(c) for c in open(os.path.join(here, 'sodax-logo-shades.txt')).read().strip()]
assert len(sh) == 128 * 48
out.append('; Logo: official SODAX lockup (gosodax/sodax-sdks docs/sodax-lockup-light.svg, MIT), 128x48, 96 tiles')
out.append('Logo:')
for ty in range(6):
    for tx in range(16):
        bs = []
        for y in range(8):
            lo = hi = 0
            for x in range(8):
                v = sh[(ty * 8 + y) * 128 + tx * 8 + x]
                lo |= (v & 1) << (7 - x); hi |= (v >> 1) << (7 - x)
            bs += [lo, hi]
        out.append('    db ' + ','.join(f'${b:02X}' for b in bs))
out.append('LogoEnd:')
open(os.path.join(here, 'font.inc'), 'w').write('\n'.join(out) + '\n')
