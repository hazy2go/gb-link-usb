#!/usr/bin/env python3
"""Case fit check: every top-side part as a box (courtyard x height from heights.json) plus the board, intersected
with the tray and the lid in OpenSCAD. Any volume > 0 is a collision (touching faces, e.g. the lid lip on the
board edge, have zero volume). Run with KiCad's Python after height_check.py --json hw/case/heights.json.
Usage: check_fit.py"""
import json, os, re, subprocess, sys, tempfile
import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
PCB = os.path.join(HERE, '..', 'rev-a', 'gb-link-usb.kicad_pcb')
X0, Y0, L = 83.3, 67.0, 63.7          # board outline (pcb_build.py)


def write_parts():
    b = pcbnew.LoadBoard(PCB)
    h = json.load(open(os.path.join(HERE, 'heights.json')))
    out = ['// generated by check_fit.py: every top part as a box (courtyard x height), board-local coordinates']
    for f in b.GetFootprints():
        r = f.GetReference()
        if r not in h:
            continue
        cy = f.GetCourtyard(pcbnew.F_CrtYd)
        bb = cy.BBox() if cy.OutlineCount() else f.GetBoundingBox(False)
        x0, x1 = bb.GetX() / 1e6 - X0, bb.GetRight() / 1e6 - X0
        y0, y1 = L - (bb.GetBottom() / 1e6 - Y0), L - (bb.GetY() / 1e6 - Y0)
        out.append(f'translate([{x0:.3f},{y0:.3f},0]) cube([{x1 - x0:.3f},{y1 - y0:.3f},{h[r]["h"]:.3f}]); // {r}')
    open(os.path.join(HERE, 'parts.scad'), 'w').write('module parts_top() {\n' + '\n'.join('  ' + l for l in out) + '\n}\n')
    return len(out) - 1


def volume(stl):
    d = open(stl, 'rb').read()
    v = [tuple(map(float, m.groups())) for m in re.finditer(rb'vertex\s+(\S+)\s+(\S+)\s+(\S+)', d)]
    vol = 0.0
    for i in range(0, len(v), 3):
        a, b, c = v[i:i + 3]
        vol += (a[0] * (b[1] * c[2] - b[2] * c[1]) - a[1] * (b[0] * c[2] - b[2] * c[0]) + a[2] * (b[0] * c[1] - b[1] * c[0])) / 6
    return abs(vol)


def main():
    n = write_parts()
    bad = False
    for which in ('tray', 'lid'):
        out = os.path.join(tempfile.mkdtemp(), which + '.stl')
        r = subprocess.run(['openscad', '--backend=manifold', '--export-format=asciistl', '-D', f'which="{which}"',
                            '-D', 'part="none"', '-o', out, os.path.join(HERE, 'check_fit.scad')], capture_output=True, text=True)
        if r.returncode and 'top level object is empty' not in r.stderr:
            sys.exit(r.stderr)
        v = volume(out) if os.path.exists(out) else 0.0        # empty intersection: nothing touches
        print(f'{which}: collision volume {v:.4f} mm3 with board + {n} parts')
        bad |= v > 1e-3
    print('RESULT:', 'FAIL' if bad else 'PASS')
    sys.exit(1 if bad else 0)


if __name__ == '__main__':
    main()
